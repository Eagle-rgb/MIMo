    def initialize(self):
        """ Called at construction and again on every embodiment hot-swap.

        Overridden to (re)resolve the MuJoCo ids the 'gravity' goal reads. 'set_embodiment'
        rebuilds 'self.model'/'self.data' from a different scene XML, which invalidates any
        cached index, and the base implementation ends by calling 'sample_goal', which for that
        goal function reads the achieved goal -- so the ids have to exist before
        'super().initialize()' runs, not after.

        The recorded reference postures are deliberately *not* re-recorded here: the gravity goal
        lives in the +-1 units of a direction cosine, which do not depend on the scene.
        """
        # Before 'super().initialize()': that ends by calling 'sample_goal', which for the
        # gravity goal runs actual resets, and those should already see the floor the episodes
        # will run on.
        self._apply_floor_properties()

        if self.goal_function == 'gravity':
            self._vestibular_site_id = self.model.site('vestibular').id
            self._gravity_body_ids = [self.model.body(name).id
                                      for name in GRAVITY_GOAL_BODIES]
            self._g_site = None
            self._g_site_time = None

        # The body is still INTACT at this point, and that is deliberate -- see the order below.
        super().initialize()

        # 1. The mask: 'self.proprioception' only exists after 'super().initialize()', and the
        #    mask is derived from its name lists.
        self._build_ghost_proprio_mask()
        if not self._ghost_active or not self._ghost_bootstrapped:
            # First call: see '_ghost_bootstrapped'. The body stays intact here.
            return
        # 2. Measure the reference (first time only), 3. remove the physics, 4. redo max_torque.
        self._measure_ghost_reference()
        self._apply_ghost_limb()
        self.actuation_model.initialize()

    @property
    def _ghost_active(self):
        """ True when a limb is missing *and* it is the runtime-patched ghost variant.

        Under ``--missing_limb_mode=cut`` the limb is already absent from the compiled model,
        so none of the ghost machinery below applies.
        """
        return self.missing_limb is not None and self.missing_limb_mode == 'ghost'

    def _ghost_subtree(self):
        """ Body, joint, geom and actuator ids of the ghost limb in the current model.

        Re-resolved on every 'initialize()', because 'set_embodiment' swaps in a different
        model and every cached id would be stale.
        """
        bodies = []
        for root_name in MISSING_LIMBS[self.missing_limb]:
            root = self.model.body(root_name).id
            bodies.append(root)
            for b in range(self.model.nbody):
                parent = b
                while parent != 0:
                    parent = self.model.body_parentid[parent]
                    if parent == root:
                        bodies.append(b)
                        break
        bodies = sorted(set(bodies))
        joints, geoms = [], []
        for b in bodies:
            joints += list(range(self.model.body_jntadr[b],
                                 self.model.body_jntadr[b] + self.model.body_jntnum[b]))
            geoms += list(range(self.model.body_geomadr[b],
                                self.model.body_geomadr[b] + self.model.body_geomnum[b]))
        actuators = [a for a in range(self.model.nu)
                     if self.model.actuator_trnid[a, 0] in joints]
        return bodies, joints, geoms, actuators

    def _apply_ghost_limb(self):
        """ Remove the limb physically without changing nq, nu or nsensordata.

        See the comment at :data:`MISSING_LIMBS` for the reasoning and the measurements. A
        no-op unless the ghost mode is active, so every stored run reloads unchanged.
        """
        if not self._ghost_active:
            return

        bodies, joints, geoms, actuators = self._ghost_subtree()
        self._ghost_bodies, self._ghost_joints, self._ghost_actuators = bodies, joints, actuators
        dofs = [self.model.jnt_dofadr[j] for j in joints]
        if not joints:
            raise RuntimeError(f"Ghost limb {self.missing_limb!r} resolved to no joints.")

        # 1) No mass, no inertia.
        self.model.body_mass[bodies] = GHOST_MASS
        self.model.body_inertia[bodies] = GHOST_INERTIA
        # 2) No collisions, and invisible -- the limb is gone, so it should not be drawn.
        self.model.geom_contype[geoms] = 0
        self.model.geom_conaffinity[geoms] = 0
        self.model.geom_rgba[geoms, 3] = 0.0
        # 3) No springs (a massless limb on a spring oscillates, see the comment at
        #    MISSING_LIMBS), heavily damped, and no torque -- a limb that is not there cannot
        #    pull. The actuators themselves stay, so the action space is unchanged.
        self.model.jnt_stiffness[joints] = 0.0
        self.model.qpos_spring[[self.model.jnt_qposadr[j] for j in joints]] = 0.0
        self.model.dof_damping[dofs] = GHOST_DAMPING
        self.model.dof_frictionloss[dofs] = 0.0
        self.model.actuator_gear[actuators, 0] = 0.0
        # 4) Pin the joints at 0 through the equality entries that every scene already carries
        #    (inactive there, with an identity polycoef).
        ghost_joint_names = {self.model.joint(j).name for j in joints}
        for e in range(self.model.neq):
            if self.model.eq_type[e] != mujoco.mjtEq.mjEQ_JOINT:
                continue
            if self.model.joint(self.model.eq_obj1id[e]).name in ghost_joint_names:
                self.model.eq_data[e, :5] = 0.0
                self.model.eq_active0[e] = 1
                self.data.eq_active[e] = 1

        # Recompute the derived constants after the mass change. 'mj_setConst' uses mjData as
        # scratch space and leaves qpos/qvel modified (measured: 5 cm of offset), so the state
        # is saved and restored around it.
        qpos, qvel = self.data.qpos.copy(), self.data.qvel.copy()
        mujoco.mj_setConst(self.model, self.data)
        self.data.qpos[:] = qpos
        self.data.qvel[:] = qvel
        mujoco.mj_forward(self.model, self.data)

    def _build_ghost_proprio_mask(self):
        """ Which proprioception entries belong to the ghost limb.

        The observation is ':meth:`SimpleProprioception.get_proprioception_obs`', i.e.
        'np.concatenate([sensor_outputs[k] for k in sorted(sensor_outputs)])' -- on this
        environment 'actuation | limits | qpos | qvel | torques'. The blocks are derived from
        the module's own name lists rather than from fixed offsets, so that a changed
        'proprio_params' cannot shift the mask silently.
        """
        if not self._ghost_active:
            self._ghost_proprio_mask = None
            self._ghost_sparse_mask = None
            return

        # Resolve the ids here rather than waiting for '_apply_ghost_limb': the mask is built
        # while the body is still intact, so that the reference can be measured on the limb.
        (self._ghost_bodies, self._ghost_joints,
         _geoms, self._ghost_actuators) = self._ghost_subtree()

        proprio = self.proprioception
        obs = proprio.get_proprioception_obs()
        blocks = proprio.sensor_outputs
        mask = np.zeros(obs.shape[0], dtype=bool)

        ghost_joint_names = {self.model.joint(j).name for j in self._ghost_joints}
        ghost_body_ids = set(self._ghost_bodies)
        ghost_actuator_ids = set(self._ghost_actuators)

        offset = 0
        for key in sorted(blocks.keys()):
            width = np.asarray(blocks[key]).size
            if key in ('qpos', 'qvel', 'limits'):
                # One entry per joint, in 'proprio.joint_names' order. That holds because every
                # 'robot:' joint is a hinge -- the root free joint is not among them, see the
                # proprioception note in CLAUDE.md.
                if width != len(proprio.joint_names):
                    raise RuntimeError(f"Proprioception block {key!r} has {width} entries for "
                                       f"{len(proprio.joint_names)} joints -- the ghost mask "
                                       "would be wrong.")
                for i, name in enumerate(proprio.joint_names):
                    if name in ghost_joint_names:
                        mask[offset + i] = True
            elif key == 'torques':
                # One torque sensor per joint group, 'sensor_dim' values wide.
                idx = offset
                for sensor_name in proprio.sensors:
                    sensor = self.model.sensor(sensor_name)
                    dim = int(sensor.dim.item())
                    site_body = self.model.site_bodyid[int(sensor.objid.item())]
                    if site_body in ghost_body_ids:
                        mask[idx:idx + dim] = True
                    idx += dim
            elif key == 'actuation':
                # 'ActuationModel.observations' is [control_input | simulation_torque], both in
                # 'self.mimo_actuators' order.
                n_act = self.n_actuators
                if width != 2 * n_act:
                    raise RuntimeError(f"Actuation block has {width} entries for {n_act} "
                                       "actuators -- the ghost mask would be wrong.")
                for i, actuator_id in enumerate(self.mimo_actuators):
                    if int(actuator_id) in ghost_actuator_ids:
                        mask[offset + i] = True
                        mask[offset + n_act + i] = True
            offset += width

        self._ghost_proprio_mask = mask
        self._ghost_sparse_mask = np.asarray(
            [name in ghost_joint_names for name in proprio.joint_names], dtype=bool)

    def _bootstrap_ghost_limb(self):
        """ Apply the ghost once the constructor has set 'init_position'.

        'initialize()' runs for the first time from inside 'super().__init__()', and
        'init_position' does not exist yet at that point -- without it
        'put_in_starting_position' and therefore 'reset_model' cannot run, and without resets
        there is no rest pose to measure. So the body stays intact through the first
        'initialize()' and is amputated here. Every later 'initialize()' (an embodiment swap
        via '--mgc') does it directly, because the flag is set by then and the reference has
        already been measured.
        """
        if not self._ghost_active:
            return
        # The WHOLE bootstrap is RNG-neutral, not just the reference measurement: the
        # 'put_in_starting_position' below draws from 'np_random' (the joint noise), and a
        # ghost run calls it once more than an intact one. Without saving the state, that one
        # extra draw would shift the random stream against a run without '--missing_limb' --
        # the same class of trap as 'sample_goal', where a surplus draw produced 94 % against
        # 98 %.
        #
        # Checked via 'reset(seed=0)': the first draws after it are bit-identical between an
        # intact and a ghost environment. The generator state right after construction is NOT a
        # valid measure for this -- it is seeded from entropy there and differs even between
        # two intact runs.
        rng_state = self.np_random.bit_generator.state
        self._ghost_bootstrapped = True
        self._measure_ghost_reference()
        self._apply_ghost_limb()
        # 'SpringDamperModel.initialize' reads 'max_torque' from 'actuator_gear'. That already
        # ran once in 'super().initialize()', but on the intact gear -- run it again after the
        # zeroing, or the control cost counts torques that no longer exist.
        self.actuation_model.initialize()
        # The ghost changes mass and collisions, so place him on the floor once more.
        self.put_in_starting_position()
        self.np_random.bit_generator.state = rng_state

    def _measure_ghost_reference(self):
        """ Measure the limb's rest pose **while it is still there**.

        What is measured is exactly what the policy sees at the start of an episode:
        'reset_model()' puts MIMo in the starting pose, lets him settle over
        'steps_after_reset' steps, and the masked channels are read afterwards. Averaged over
        'ghost_reference_samples' ISR-free resets, because a single reset would pin the
        reference to one draw of the joint noise -- the same argument as in
        ':meth:`.create_prone_and_supine_reference_goals`'.

        **Why the rest pose rather than 0.** A constant 0 is outside the policy's training
        distribution: 'robot:left_knee' rests at -0.115 rad, not at 0 (measured, n=20, supine).
        A zero-shot transfer would then have measured two causes at once -- the missing limb
        and the distribution shift. With the rest pose the channel reports something the policy
        has already seen thousands of times.

        That this is not cosmetic is measured: the same intact PPO policy reaches 30 % full
        roll on 'missing_limb=left_arm' with 'rest' against 10 % with 'zero' (rho_max 0.510
        against 0.418, 20 episodes). On 'left_leg' it changes nothing (0 % either way) -- the
        leg really is needed, whereas for the arm part of the drop was the shift.

        Read deliberately through 'self.proprioception.get_proprioception_obs()' rather than
        ':meth:`.get_proprio_obs`': the latter would already apply the mask and the reference
        would be measured from itself.

        Measured once per environment. An embodiment swap ('--mgc') inherits it: the reference
        describes the rest pose, and re-measuring mid-training would shift the observation
        under the policy.
        """
        if not self._ghost_active or self.ghost_obs != 'rest':
            self._ghost_reference = None
            self._ghost_sparse_reference = None
            return
        if self._ghost_reference is not None:
            return

        rng_state = self.np_random.bit_generator.state
        saved_isr = self.isr
        self.isr = False
        # Measure from a fixed seed, not from the ambient generator -- see GHOST_REFERENCE_SEED.
        # The state is restored in the 'finally' below, so the episode stream is untouched.
        self.np_random.bit_generator.state = \
            np.random.default_rng(GHOST_REFERENCE_SEED).bit_generator.state
        try:
            full, sparse = [], []
            for _ in range(self.ghost_reference_samples):
                self.reset_model()
                full.append(np.asarray(self.proprioception.get_proprioception_obs(),
                                       dtype=np.float64)[self._ghost_proprio_mask])
                sparse.append(np.asarray(self.proprioception.get_sparse_proprioception_obs(),
                                         dtype=np.float64)[self._ghost_sparse_mask])
            full = np.asarray(full, dtype=np.float64)
            sparse = np.asarray(sparse, dtype=np.float64)
            self._ghost_reference = full.mean(axis=0)
            self._ghost_sparse_reference = sparse.mean(axis=0)
            if self._ghost_reference.size == 0:
                raise RuntimeError("The ghost mask is empty -- nothing would be replaced.")
            spread = full.std(axis=0)
            print(f"Ghost reference '{self.missing_limb}' ({self.starting_position}, "
                  f"n={self.ghost_reference_samples}): {self._ghost_reference.size} channels, "
                  f"magnitude mean {np.abs(self._ghost_reference).mean():.4f} / "
                  f"max {np.abs(self._ghost_reference).max():.4f}, "
                  f"spread max {spread.max():.4f}")
        finally:
            self.isr = saved_isr
            self.np_random.bit_generator.state = rng_state

    def get_proprio_obs(self, sparse=False):
        """ Proprioception, with a constant value for a ghost limb.

        The limb is physically gone, so it must not report anything current: the masked
        channels are pulled to a constant. Which one is decided by '--ghost_obs' -- the value
        measured on the intact body at rest ('rest', the default, see
        ':meth:`._measure_ghost_reference`') or 0 ('zero'). Without the mask the actuation
        channels in particular would mirror the policy's own command back at it.

        Masked before observation normalisation, i.e. at the sensor level.
        """
        obs = super().get_proprio_obs(sparse)
        mask = self._ghost_sparse_mask if sparse else self._ghost_proprio_mask
        if mask is None or obs.shape[0] != mask.shape[0]:
            return obs
        reference = self._ghost_sparse_reference if sparse else self._ghost_reference
        obs = obs.copy()
        # 'reference is None' means ghost_obs='zero'; during the reference measurement itself it
        # is None too, but '_measure_ghost_reference' reads past the module there anyway.
        obs[mask] = 0.0 if reference is None else reference
        return obs

    def _apply_floor_properties(self):
        """ Make the floor compliant, or change its friction ('--floor_softness' and friends).

        02.09.2026 The floor is a single plane geom, identical in all sixteen age scenes, and
        carries no contact parameters of its own -- it inherits MuJoCo's global defaults. The
        parameters are written onto the compiled model here rather than into the XMLs, because
        the age scenes are pre-generated and 'set_embodiment' swaps between them: sixteen copies
        of the same four numbers would rot, and a runtime patch sweeps from the CLI.
        'initialize' runs at construction and again on every embodiment hot-swap, so a
        swapped-in scene gets the same floor.

        **'geom_priority' is the part that is easy to get wrong.** MuJoCo mixes the contact
        parameters of the two geoms in a pair: at equal priority 'solref'/'solimp' are a
        solmix-weighted average and 'friction' is the elementwise maximum. MIMo's skin is
        'solref="0.005 1"', so averaging drags any soft floor back towards rigid -- asking for
        'solref 0.10' produced an effective 0.0525 and a fifth of the intended give (0.87 mm of
        sink instead of 4.50 mm, measured). Raising the floor's priority makes its parameters
        win outright, which is also the only way friction can be lowered rather than only
        raised.

        The flip side of that priority is why the untouched parameters are pinned to the
        baseline mixture below: raising the priority would otherwise replace them too, so a
        friction-only run would silently also change the contact stiffness and the flags would
        not be independent.

        What this does and does not model: the plane does not deform, MIMo simply penetrates it,
        so this is a compliant *contact*, not a visible mat. That is deliberate -- the deflection
        is millimetres, and a MuJoCo 'flex' deformable under MIMo's ~37 collision geoms at
        200 Hz would dominate the step cost to reproduce it. If the mat has to be visible in a
        figure, add a slab geom to the scene instead, and note that 'get_minimal_z_coordinate'
        measures against z = 0.
        """
        if (self.floor_softness is None and self.floor_friction is None
                and self.floor_solimp_width is None):
            return

        floor_id = self.model.geom('floor').id

        # Idempotence guard: the baseline mixture below is read off the floor geom itself, so a
        # second pass over an already-patched model would read back our own values. No shipped
        # scene sets a priority, so a non-zero one means this already ran on this model.
        if self.model.geom_priority[floor_id] != 0:
            return

        # A representative MIMo geom. All of them come from the same 'mimo' default class, so
        # any one carries the skin's contact parameters. Body 0 is the worldbody.
        skin_id = next(i for i in range(self.model.ngeom) if self.model.geom_bodyid[i] != 0)

        # What MuJoCo would have computed for this pair without a priority. Both solrefs are
        # positive here, which is the case where the mix is a weighted average; had either been
        # in the negative (direct stiffness/damping) form, MuJoCo would take the elementwise
        # minimum instead.
        weight = (self.model.geom_solmix[floor_id]
                  / (self.model.geom_solmix[floor_id] + self.model.geom_solmix[skin_id]))
        baseline_solref = (weight * self.model.geom_solref[floor_id]
                           + (1.0 - weight) * self.model.geom_solref[skin_id])
        baseline_solimp = (weight * self.model.geom_solimp[floor_id]
                           + (1.0 - weight) * self.model.geom_solimp[skin_id])
        baseline_friction = np.maximum(self.model.geom_friction[floor_id],
                                       self.model.geom_friction[skin_id])

        if self.floor_softness is not None:
            min_timeconst = 2.0 * self.model.opt.timestep
            if self.floor_softness < min_timeconst:
                print(f"Warning! --floor_softness={self.floor_softness} is below twice the "
                      f"simulation timestep ({min_timeconst}). MuJoCo cannot resolve a contact "
                      "time constant shorter than that, so the floor will be stiffer than "
                      "requested.")
            # solref = (time constant, damping ratio); the ratio stays critically damped.
            solref = np.array([self.floor_softness, 1.0])
        else:
            solref = baseline_solref

        if self.floor_solimp_width is not None:
            # solimp = (dmin, dmax, width, midpoint, power). Ramping from dmin = 0 to dmax over
            # 'width' of penetration is the progressive response of foam -- soft at the surface,
            # firm once compressed -- rather than the linear spring 'floor_softness' gives.
            solimp = np.array([0.0, 0.95, self.floor_solimp_width, 0.5, 2.0])
        else:
            solimp = baseline_solimp

        friction = baseline_friction.copy()
        if self.floor_friction is not None:
            # Sliding friction only. The torsional and rolling coefficients differ between the
            # plane and the skin in the fourth decimal and are left at the baseline mixture.
            friction[0] = self.floor_friction

        self.model.geom_solref[floor_id] = solref
        self.model.geom_solimp[floor_id] = solimp
        self.model.geom_friction[floor_id] = friction
        # Last: everything above is only reachable because the floor now outranks MIMo's skin.
        self.model.geom_priority[floor_id] = 1

    def create_prone_and_supine_reference_goals(self):
        """ Record the reference goal vector in prone and in supine ('gravity' only).

        These are the two 'desired_goal's: starting prone, the target is the supine reference,
        and vice versa. Both are recorded once, at construction.

        Two things differ from a naive single-shot implementation, and both were bugs waiting to
        happen:

        * The reference is **averaged over 'gravity_reference_samples' resets with ISR off**. A
          single reset fixes the goal at one draw of the initial joint noise -- 'head_swivel' in
          particular settles anywhere within a wide range -- and MIMo would then be scored on
          reproducing that specific draw rather than on the posture.
        * The RNG state is **saved and restored** around the recording. The reference resets draw
          from 'self.np_random', the same generator that produces the initial joint noise of every
          training episode, so without this the number of samples taken here would silently shift
          which episodes the run sees. This is the same failure that made evaluation depend on
          whether the goal was pinned via goal_low/goal_high (measured 94% vs 98%); see
          ':meth:`.sample_goal`'.
        """
        rng_state = self.np_random.bit_generator.state
        saved_isr = self.isr
        saved_position = self.starting_position
        self.isr = False

        try:
            for position in ('prone', 'supine'):
                self.starting_position = position
                samples = []
                for _ in range(self.gravity_reference_samples):
                    self.reset_model()
                    samples.append(np.asarray(self.get_achieved_goal(), dtype=np.float64))
                samples = np.asarray(samples, dtype=np.float64)
                reference = samples.mean(axis=0)
                spread = samples.std(axis=0)

                if position == 'prone':
                    self.prone_reference_goal = reference
                else:
                    self.supine_reference_goal = reference
                self.reference_goal_std[position] = spread

                print(f"Reference goal ({position}, n={self.gravity_reference_samples}):")
                for label, value, sd in zip(self.goal_labels(), reference, spread):
                    print(f"    {label:<22} {value:+.3f}  (sd {sd:.3f})")
        finally:
            self.isr = saved_isr
            self.starting_position = saved_position
            self.np_random.bit_generator.state = rng_state
            self.reference_goals_created = True

    def goal_labels(self):
        """ Names of the goal dimensions, in order. For logging and diagnostics. """
        if self.goal_function == 'gravity':
            return [f'gravity_x_in_{name}_frame' for name in GRAVITY_GOAL_BODIES]

