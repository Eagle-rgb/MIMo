# 04.09.2026 Missing limbs. Two modes, and which one you want depends on whether a policy
# has to survive the change.
#
#   '--missing_limb_mode=cut'    The limb is really gone. The body subtree is deleted from the
#                                XML, so its joints, actuators and sensors go with it and the
#                                spaces shrink -- 46 -> 38 actuators and 305 -> 253
#                                proprioception values for one limb. This is the mode for
#                                TRAINING a policy that never had the limb. The scenes are
#                                pre-generated by
#                                'mimoEnv/assets/roll_over/generate_amputated_scenes.py';
#                                nothing is written at runtime, for the same reason the age
#                                scenes are pre-generated (parallel cluster runs raced on
#                                creating and deleting temporary scenes).
#
#   '--missing_limb_mode=ghost'  The limb is gone physically but its joints, actuators and
#                                sensors stay, so nq, nu and the observation width are
#                                unchanged. This is the mode for TRANSFER: an intact-trained
#                                policy can be loaded onto it, either to continue training
#                                ('--load_model') or to be evaluated zero-shot. A cut model
#                                cannot -- SB3 refuses with "Observation spaces do not match".
#
# The ghost is a runtime patch on the compiled model in 'initialize()', not an XML variant --
# the same pattern as '_apply_floor_properties', and for the same reason: 'set_embodiment'
# swaps between pre-generated age scenes, and sixteen more copies would rot.
#
#   * body_mass / body_inertia         -> ~0   the limb no longer weighs anything
#   * geom_contype / geom_conaffinity  -> 0    it collides with nothing
#   * geom_rgba alpha                  -> 0    it is not drawn
#   * jnt_stiffness / qpos_spring      -> 0    no spring left (see below)
#   * dof_damping -> GHOST_DAMPING, actuator_gear -> 0
#   * the joint-equality entries already present in every scene are activated and set to
#     polycoef 0, which pins the limb at qpos = 0
#
# Verified against the cut model: the remaining mass and the centre of mass of the remaining
# bodies agree **exactly** (|diff| = 0.0e+00 for left_arm as well as left_leg), and over 600
# noisy steps the ghost limb stays at exactly qpos = 0 and qvel = 0.
#
# **The springs have to go.** A massless limb on a spring of stiffness 1.7-3.5 oscillates at
# ~18 rad/s and the soft equality constraint does not hold it: measured max|qvel| 8.4 with the
# springs against 0.0000 without. It does not feed back into MIMo's dynamics (no mass, no
# collision), but it costs solver work and looks broken in a render. Zeroing 'actuator_gear'
# alone is NOT enough -- the flailing comes from the joint springs, not from the actuators
# (measured: 8.41 with gear=0 against 8.40 with gear on).
#
# **'mj_setConst' uses mjData as scratch space.** After patching the masses the derived
# constants ('body_subtreemass', 'dof_M0') have to be recomputed or the dynamics are wrong,
# but 'mj_setConst' leaves 'data.qpos' modified -- 5 cm of offset in the body positions,
# measured -- so the state is saved and restored around it.
